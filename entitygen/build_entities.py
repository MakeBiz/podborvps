def build_page(e):
    slug=e["slug"]; url="https://podborvps.ru/%s/"%slug
    h=head
    h=re.sub(r"<title>.*?</title>","<title>%s — ПодборVPS</title>"%html.escape(e["title"]),h,flags=re.S)
    h=re.sub(r'<meta name="description" content=".*?">','<meta name="description" content="%s">'%html.escape(e["desc"]),h,flags=re.S)
    h=re.sub(r'<link rel="canonical" href=".*?">','<link rel="canonical" href="%s">'%url,h,flags=re.S)
    h=re.sub(r'<meta property="og:title" content=".*?">','<meta property="og:title" content="%s">'%html.escape(e["title"]),h,flags=re.S)
    h=re.sub(r'<meta property="og:description" content=".*?">','<meta property="og:description" content="%s">'%html.escape(e["desc"]),h,flags=re.S)
    h=re.sub(r'<meta property="og:url" content=".*?">','<meta property="og:url" content="%s">'%url,h,flags=re.S)
    graph=[
     {"@type":"WebPage","name":e["title"],"description":e["desc"],"url":url,"inLanguage":"ru-RU",
      "isPartOf":{"@type":"WebSite","name":"ПодборVPS","url":"https://podborvps.ru/"},
      "publisher":{"@type":"Organization","name":"ПодборVPS","url":"https://podborvps.ru/"}},
     {"@type":"BreadcrumbList","itemListElement":[
       {"@type":"ListItem","position":1,"name":"Главная","item":"https://podborvps.ru/"},
       {"@type":"ListItem","position":2,"name":e["title"],"item":url}]},
     {"@type":"FAQPage","mainEntity":[{"@type":"Question","name":q,"acceptedAnswer":{"@type":"Answer","text":a}} for q,a in e["faq"]]},
    ]
    ld=json.dumps({"@context":"https://schema.org","@graph":graph},ensure_ascii=False)
    h=re.sub(r'<script type="application/ld\+json">.*?</script>','<script type="application/ld+json">%s</script>'%ld,h,flags=re.S,count=1)
    tag="Гео" if e["kind"]=="geo" else "Задача"
    crumbs='<div class="crumbs"><a href="/">Главная</a> → %s</div>'%html.escape(e["title"])
    body='<article><div class="kicker"><span class="tag">%s</span></div><h1>%s</h1><p class="lead">%s</p>'%(tag,html.escape(e["title"]),html.escape(e["lead"]))
    for p in e["paras"]: body+="<p>%s</p>"%html.escape(p)
    label="Подходит для" if e["kind"]=="geo" else "Рекомендуемая конфигурация"
    val=e["best"] if e["kind"]=="geo" else e["cfg"]
    body+='<div class="card"><h2>%s</h2><p style="margin:0">%s</p></div>'%(label,html.escape(val))
    body+='<h2>Частые вопросы</h2>'
    for q,a in e["faq"]:
        body+='<h2 style="font-size:18px;margin:20px 0 6px">%s</h2><p>%s</p>'%(html.escape(q),html.escape(a))
    body+=('<div class="card alt"><h2>Подобрать сервер под задачу</h2>'
      '<p style="margin:0 0 18px">Задайте ресурсы, географию и бюджет — калькулятор отсортирует провайдеров под вашу задачу.</p>'
      '<a class="btn ghost" href="/#calc">Открыть калькулятор →</a></div></article>')
    footer='<footer><div class="wrap" style="max-width:1180px">'+FNAV+DISC+'</div></footer>'
    return h+"</head>\n<body>"+header_html+'<main class="wrap">'+crumbs+body+"</main>\n"+footer+"\n</body>\n</html>\n"

